#!/usr/bin/env python3
"""Merges `LiminalTests --calibrate-loudness a b` output into Source/DSP/LevelMatchTable.h.

Each instrument's trim in a place and Character is the difference between the Forgotten Piano's
loudness there and its own (dB): the piano (the default instrument, and the reference the library's
dry levels were already matched to) is never changed, so every place keeps the level and the balance
against its room that it had, and the other nineteen are brought to the piano. Usage:
  levelmatch.py out.h calibration-1.txt [calibration-2.txt ...]
"""
import sys

out, inputs = sys.argv[1], sys.argv[2:]
level = {}
for path in inputs:
    for line in open(path):
        if line.startswith("LOUDNESS "):
            _, w, p, c, v = line.split()
            level[(int(w), int(p), int(c))] = float(v)
places, characters, instruments = 10, 3, 20
missing = [(w, p, c) for w in range(instruments) for p in range(places) for c in range(characters) if (w, p, c) not in level]
if missing:
    sys.exit(f"missing {len(missing)} measurements, e.g. {missing[:3]}")
mean = {(p, c): level[(0, p, c)] for p in range(places) for c in range(characters)}   # the piano
# Cassette Strings was raised by 2.5 dB the day before (2026-11-05): re-checked, it is never more than
# 1.1 dB under the piano, so the table only ever lowers it (where a room makes it louder), never raises it.
never_raise = {15}
trim = lambda w, p, c: min(0.0, mean[(p, c)] - level[(w, p, c)]) if w in never_raise else mean[(p, c)] - level[(w, p, c)]
rows = []
for w in range(instruments):
    cells = []
    for p in range(places):
        cells.append("{ " + ", ".join(f"{trim(w, p, c):.2f}f" for c in range(characters)) + " }")
    rows.append("    { " + ", ".join(cells) + " },")
with open(out, "w") as f:
    f.write("// Generated by tools/levelmatch/levelmatch.py from `LiminalTests --calibrate-loudness` (Source/DSP/LevelMatch.h).\n"
            "// dB per instrument (params::libraryNames order) x place (dsp::Place order) x Character. Do not edit by hand.\n"
            "inline constexpr float table[instruments][placeCount][characterCount] {\n" + "\n".join(rows) + "\n};\n")
worst = max(abs(trim(w, p, c)) for (w, p, c) in level)
print(f"wrote {out}: {len(level)} measurements, largest trim {worst:.2f} dB")
